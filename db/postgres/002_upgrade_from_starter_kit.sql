-- Upgrade an existing `lapus` schema created by the original starter-kit script.
--
-- Run this ONCE, as an administrator, if `lapus` already exists in your
-- Spec_Stage from before the schema was generated from the application code.
-- If you are creating the schema for the first time, run
-- 001_lapus_schema.sql instead and skip this file entirely.
--
-- Why this exists: 001_lapus_schema.sql uses CREATE TABLE IF NOT EXISTS, so
-- applying it over an older `lapus` schema silently does nothing at all. The
-- tables keep their old shape, and the application then fails on a column that
-- was never added. Only ALTER can move an existing schema forward.
--
-- It is idempotent: running it twice is harmless.

BEGIN;

-- 1. The column every change item writes. Its absence broke every write on
--    PostgreSQL: the application records "propose that this field be empty"
--    separately from "no value proposed", which a nullable proposed_value
--    cannot express on its own.
ALTER TABLE lapus.change_item
    ADD COLUMN IF NOT EXISTS clears_value INTEGER NOT NULL DEFAULT 0;

-- 2. Remove every foreign key from lapus into the parser-owned public schema.
--
--    The parser deletes and reinserts documents on each rerun. ON DELETE
--    RESTRICT blocks that rerun; ON DELETE CASCADE silently destroys the
--    user's change requests along with the staging rows. Either way the
--    application must not constrain parser-owned data -- see
--    docs/adr/0001-staging-overlay-model.md. Referential integrity against
--    staging is checked in the service layer, where a missing document is a
--    reportable state rather than a constraint violation.
--
--    The constraint names are generated by PostgreSQL and vary, so they are
--    discovered rather than hard-coded.
DO $$
DECLARE
    offending RECORD;
BEGIN
    FOR offending IN
        SELECT DISTINCT tc.table_name, tc.constraint_name
        FROM information_schema.table_constraints tc
        JOIN information_schema.constraint_column_usage ccu
          ON tc.constraint_name = ccu.constraint_name
         AND tc.table_schema = ccu.constraint_schema
        WHERE tc.constraint_type = 'FOREIGN KEY'
          AND tc.table_schema = 'lapus'
          AND ccu.table_schema <> 'lapus'
    LOOP
        EXECUTE format('ALTER TABLE lapus.%I DROP CONSTRAINT %I',
                       offending.table_name, offending.constraint_name);
        RAISE NOTICE 'dropped foreign key %.% into parser-owned data',
                     offending.table_name, offending.constraint_name;
    END LOOP;
END $$;

-- 3. Replace the plain UNIQUE constraint with two partial indexes.
--
--    target_record_id is NULL for one-row-per-document sections, and in SQL a
--    NULL never equals a NULL -- so a single UNIQUE permitted duplicate
--    proposals against exactly the single-record sections it was meant to
--    protect. Splitting on the NULL closes that gap.
DO $$
DECLARE
    old_constraint TEXT;
BEGIN
    SELECT tc.constraint_name INTO old_constraint
    FROM information_schema.table_constraints tc
    WHERE tc.table_schema = 'lapus'
      AND tc.table_name = 'change_item'
      AND tc.constraint_type = 'UNIQUE'
    LIMIT 1;

    IF old_constraint IS NOT NULL THEN
        EXECUTE format('ALTER TABLE lapus.change_item DROP CONSTRAINT %I', old_constraint);
        RAISE NOTICE 'dropped UNIQUE constraint %', old_constraint;
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ux_lapus_change_item_row_target
    ON lapus.change_item(request_id, target_table, target_record_id, target_field)
    WHERE target_record_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_lapus_change_item_doc_target
    ON lapus.change_item(request_id, target_table, target_field)
    WHERE target_record_id IS NULL;

-- 4. The version marker the application checks at startup.
CREATE TABLE IF NOT EXISTS lapus.schema_version (
    version INTEGER NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO lapus.schema_version (version)
SELECT 1
WHERE NOT EXISTS (SELECT 1 FROM lapus.schema_version);

-- 5. Drop the starter kit's helper views.
--
--    Lapus never queried them -- the repositories build their own SQL -- and
--    they join lapus tables to public.t00_documents, which is the coupling
--    this upgrade exists to remove. Drop rather than leave: a view depending
--    on a staging table can block a parser operation that drops it.
DROP VIEW IF EXISTS lapus.v_change_request_summary;
DROP VIEW IF EXISTS lapus.v_spec_change_history;

COMMIT;
